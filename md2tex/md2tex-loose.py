# ---------------------------------------------------------------------------
# 解析器
# ---------------------------------------------------------------------------

class State:
    NORMAL = "normal"
    IN_UL = "in_ul"
    IN_OL = "in_ol"
    IN_CODE = "in_code"
    IN_TABLE = "in_table"
    IN_BLOCKQUOTE = "in_bq"


class Md2Tex:
    def __init__(self, columns=2):
        self.columns = columns
        self.state = State.NORMAL
        self.list_depth = 0
        self.table_buffer = []
        self.code_buffer = []
        self.bq_buffer = []
        self.output_lines = []
        self._inside_list_stack = []
        self.large_tables = []

    def convert(self, md_text: str) -> tuple[str, list[str]]:
        lines = md_text.splitlines()
        i = 0
        while i < len(lines):
            line = lines[i]

            if line.strip().startswith("```"):
                if self.state != State.IN_CODE:
                    self._flush_any()
                    self.state = State.IN_CODE
                    self.code_buffer = []
                else:
                    self._emit_code_block()
                    self.state = State.NORMAL
                i += 1
                continue

            if self.state == State.IN_CODE:
                self.code_buffer.append(line)
                i += 1
                continue

            if line.strip() == "":
                self._flush_any()
                self._close_lists_if_needed(0)
                i += 1
                continue

            if re.fullmatch(r"\s*-{3,}\s*", line):
                self._flush_any()
                self._close_lists_if_needed(0)
                self._emit("\\csheetrule")
                i += 1
                continue

            if self._is_table_line(line):
                if self.state != State.IN_TABLE:
                    self._flush_any()
                    self.state = State.IN_TABLE
                    self.table_buffer = []
                self.table_buffer.append(line)
                i += 1
                continue
            elif self.state == State.IN_TABLE:
                self._emit_table()
                self.state = State.NORMAL
                continue

            if line.strip().startswith(">"):
                if self.state != State.IN_BLOCKQUOTE:
                    self._flush_any()
                    self.state = State.IN_BLOCKQUOTE
                    self.bq_buffer = []
                self.bq_buffer.append(line)
                i += 1
                continue
            elif self.state == State.IN_BLOCKQUOTE:
                self._emit_blockquote()
                self.state = State.NORMAL
                continue

            m = re.match(r"^(#{1,6})\s+(.*)", line)
            if m:
                self._flush_any()
                self._close_lists_if_needed(0)
                level = len(m.group(1))
                text = self._inline(m.group(2))
                self._emit_heading(level, text)
                i += 1
                continue

            ul_match = re.match(r"^(\s*)[-*+]\s+(.*)", line)
            ol_match = re.match(r"^(\s*)\d+\.\s+(.*)", line)
            if ul_match or ol_match:
                self._flush_any()
                indent = len((ul_match or ol_match).group(1))
                text = self._inline((ul_match or ol_match).group(2))
                self._handle_list_item("ul" if ul_match else "ol", indent, text)
                i += 1
                continue

            self._flush_any()
            self._emit_paragraph(self._inline(line))
            i += 1

        self._flush_any()
        self._close_lists_if_needed(0)

        return "\n".join(self.output_lines), self.large_tables

    def _flush_any(self):
        if self.state == State.IN_TABLE:
            self._emit_table()
            self.state = State.NORMAL
        elif self.state == State.IN_BLOCKQUOTE:
            self._emit_blockquote()
            self.state = State.NORMAL

    def _emit(self, text):
        self.output_lines.append(text)

    def _emit_heading(self, level, text):
        if level == 1:
            return
        elif level == 2:
            self._emit(f"\\section*{{{text}}}")
        elif level == 3:
            self._emit(f"\\subsection*{{{text}}}")
        else:
            self._emit(f"\\subsubsection*{{{text}}}")

    def _handle_list_item(self, list_type, indent, text):
        if not self._inside_list_stack:
            env = "itemize" if list_type == "ul" else "enumerate"
            self._emit(f"\\begin{{{env}}}")
            self._inside_list_stack.append(env)
        self._emit(f"  \\item {text}")

    def _close_lists_if_needed(self, target_depth):
        while self._inside_list_stack:
            env = self._inside_list_stack.pop()
            self._emit(f"\\end{{{env}}}")

    def _emit_paragraph(self, text):
        self._emit(text + "\\par")

    def _is_table_line(self, line):
        stripped = line.strip()
        if not stripped.startswith("|") and not stripped.startswith("+-"):
            return False
        parts = stripped.split("|")
        return len(parts) >= 3

    def _emit_table(self):
        if not self.table_buffer:
            return

        lines = self.table_buffer
        data_lines = []
        for ln in lines:
            s = ln.strip()
            if re.fullmatch(r"[\s+|\-+:]+", s.replace(" ", "")):
                continue
            data_lines.append(s)

        if not data_lines:
            return

        first = data_lines[0].strip()
        parts = first.split("|")
        if parts and parts[0].strip() == "":
            parts = parts[1:]
        if parts and parts[-1].strip() == "":
            parts = parts[:-1]
        num_cols = len(parts)

        if num_cols == 0:
            return

        use_strip = num_cols >= STRIP_TABLE_COL_THRESHOLD

        if use_strip:
            col_spec = "l" * num_cols
        elif num_cols == 2:
            col_spec = r"p{0.37\columnwidth}p{0.57\columnwidth}"
        elif num_cols == 3:
            col_spec = r"p{0.28\columnwidth}p{0.28\columnwidth}p{0.38\columnwidth}"
        else:
            col_spec = "l" * num_cols

        tabular_lines = []
        tabular_lines.append(f"\\begin{{csheettable}}{{{col_spec}}}")

        for idx, ln in enumerate(data_lines):
            parts = ln.split("|")
            if parts and parts[0].strip() == "":
                parts = parts[1:]
            if parts and parts[-1].strip() == "":
                parts = parts[:-1]
            if len(parts) != num_cols:
                continue
            if idx == 0:
                row_parts = []
                for c in parts:
                    processed = self._inline(c.strip())
                    row_parts.append(f"\\tblheader{{{processed}}}")
                tabular_lines.append(" & ".join(row_parts) + " \\\\")
                tabular_lines.append("\\midrule")
            else:
                row_parts = []
                for c in parts:
                    processed = self._inline(c.strip())
                    row_parts.append(processed)
                tabular_lines.append(" & ".join(row_parts) + " \\\\")

        tabular_lines.append("\\end{csheettable}")
        tabular_body = "\n".join(tabular_lines)

        if use_strip:
            self.large_tables.append(tabular_body)
        else:
            self._emit(tabular_body)

    def _emit_code_block(self):
        if not self.code_buffer:
            return
        self._emit("\\begin{csheetcode}")
        for line in self.code_buffer:
            self._emit(line)
        self._emit("\\end{csheetcode}")

    def _emit_blockquote(self):
        if not self.bq_buffer:
            return
        lines = []
        for ln in self.bq_buffer:
            s = ln.strip()
            if s.startswith(">"):
                s = s[1:].strip()
            lines.append(self._inline(s))
        content = " ".join(lines)
        self._emit(f"\\textit{{{content}}}\\par")

    def _inline(self, text: str) -> str:
        display_math = {}
        dm_counter = [0]
        def save_dm(m):
            key = f"<DM{dm_counter[0]}>"
            dm_counter[0] += 1
            display_math[key] = self._handle_display_math(m.group(1).strip())
            return key
        text = re.sub(r"(?<!\\)\$\$(.+?)\$\$", save_dm, text, flags=re.DOTALL)

        inline_math = {}
        im_counter = [0]
        def save_im(m):
            key = f"<IM{im_counter[0]}>"
            im_counter[0] += 1
            inline_math[key] = m.group(0)
            return key
        text = re.sub(r"(?<!\\)\$([^$]+?)\$", save_im, text)

        def bold_repl(m):
            return r"\csheetbold{" + m.group(1) + "}"
        text = re.sub(r"\*\*(.+?)\*\*", bold_repl, text)
        text = re.sub(r"__(.+?)__", bold_repl, text)

        text = re.sub(r"\[([^\]]+)\]\([^)]+\)", lambda m: m.group(1), text)

        def strike_repl(m):
            return r"\csheetstrike{" + m.group(1) + "}"
        text = re.sub(r"~~(.+?)~~", strike_repl, text)

        def code_repl(m):
            return r"\csheetcodeinline{" + m.group(1) + "}"
        text = re.sub(r"`(.+?)`", code_repl, text)

        text = self._escape_inline(text)

        for key, val in display_math.items():
            text = text.replace(key, val, 1)
        for key, val in inline_math.items():
            text = text.replace(key, val, 1)

        return text

    def _escape_inline(self, text: str) -> str:
        text = text.replace("&", r"\&")
        text = text.replace("%", r"\%")
        text = text.replace("$", r"\$")
        text = text.replace("#", r"\#")
        text = text.replace("_", r"\_")
        text = text.replace("~", r"\textasciitilde{}")
        text = text.replace("^", r"\textasciicircum{}")
        for ch, replacement in ARROW_MAP.items():
            text = text.replace(ch, replacement)
        text = text.replace("->", r"$\rightarrow$")
        text = text.replace("<-", r"$\leftarrow$")
        for ch, replacement in SUBSCRIPT_MAP.items():
            text = text.replace(ch, replacement)
        return text

    def _handle_display_math(self, math: str) -> str:
        math = math.replace("$", "")
        for ch, replacement in ARROW_MAP.items():
            math = math.replace(ch, replacement)
        math = math.replace("->", r"\rightarrow")
        math = math.replace("<-", r"\leftarrow")
        return f"\\[{math}\\]"


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(description="Convert Markdown Cheat Sheet to XeLaTeX (loose layout)")
    parser.add_argument("input", help="Input Markdown file")
    parser.add_argument("-o", "--output", help="Output .tex file")
    parser.add_argument("-c", "--columns", type=int, default=2, help="Number of columns (default: 2)")
    args = parser.parse_args()

    in_path = Path(args.input)
    if not in_path.exists():
        print(f"Error: file not found: {in_path}", file=sys.stderr)
        sys.exit(1)

    out_path = Path(args.output) if args.output else in_path.with_suffix(".tex")

    md_text = in_path.read_text(encoding="utf-8")

    converter = Md2Tex(columns=args.columns)
    body, large_tables = converter.convert(md_text)

    large_table_blocks = []
    i = 0
    while i < len(large_tables):
        if i + 1 < len(large_tables):
            block = (
                "\\begin{table*}\n"
                "\\centering\n"
                "\\begin{minipage}{0.45\\textwidth}\n"
                "\\centering\n"
                f"{large_tables[i]}\n"
                "\\end{minipage}%\n"
                "\\hfill\n"
                "\\begin{minipage}{0.45\\textwidth}\n"
                "\\centering\n"
                f"{large_tables[i+1]}\n"
                "\\end{minipage}\n"
                "\\end{table*}\n"
            )
            large_table_blocks.append(block)
            i += 2
        else:
            block = (
                "\\begin{table*}\n"
                "\\centering\n"
                "\\begin{minipage}{0.45\\textwidth}\n"
                "\\centering\n"
                f"{large_tables[i]}\n"
                "\\end{minipage}\n"
                "\\end{table*}\n"
            )
            large_table_blocks.append(block)
            i += 1

    large_tables_tex = "\n".join(large_table_blocks)

    preamble = PREAMBLE_TEMPLATE.format(
        source_name=in_path.name,
        num_columns=args.columns
    )

    tex = f"""{preamble}{body}
% -------------------- Large Tables (>=6 cols) --------------------
\\end{{multicols}}
{large_tables_tex}
\\end{{document}}
"""

    out_path.write_text(tex, encoding="utf-8")
    print(f"Written: {out_path}")


if __name__ == "__main__":
    main()

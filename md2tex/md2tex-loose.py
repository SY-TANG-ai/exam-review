"""
md2tex-loose.py — Convert Markdown Cheat Sheet to generous XeLaTeX (loose layout)

For exam-review skill — produces a comfortable, easy-to-read printable PDF.

Loose layout:
  - A4 portrait, 1cm margins
  - 2 columns (configurable)
  - 7pt Verdana, lineskip = 9pt
  - Tables >=6 cols → table* + minipage after multicols

Usage:
    python md2tex-loose.py input.md [--output output.tex] [--columns N]
"""


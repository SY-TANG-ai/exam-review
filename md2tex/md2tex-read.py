CIRCLED = {
    '①': '(1)', '②': '(2)', '③': '(3)', '④': '(4)', '⑤': '(5)',
    '⑥': '(6)', '⑦': '(7)', '⑧': '(8)', '⑨': '(9)', '⑩': '(10)',
}

# 装饰性标记：XeLaTeX 排不出、删掉也不损失信息
STRIP_MARKS = (
    '\U0001F4CC'   # 📌 知识点卡片标记
    '\U0001F534\U0001F7E1\U0001F7E2\U0001F535\U000026AA\U0001F7E0'  # 🔴🟡🟢🔵⚪🟠 优先级圆点
    '\U0001F3AF'   # 🎯
    '\U00002757\U0000203C'  # ❗‼
)

MATH_SYMBOLS = {
    '★': r'$\bigstar$',
    '⭐': r'$\bigstar$',
    '◉': r'$\odot$',        # UML final node / bull's eye
    '⊗': r'$\otimes$',      # flow final
    '●': r'$\bullet$',      # UML initial node
    '◇': r'$\diamond$',     # UML aggregation
    '◆': r'$\blacklozenge$',# UML composition
    '△': r'$\triangle$',    # UML generalisation
    '✕': r'$\otimes$',      # flow-final marker
    'Ⓗ': '(H)',             # history pseudo-state（无对应数学符号）
    '✓': r'$\checkmark$',
    '✅': r'$\checkmark$',
    '✗': r'$\times$',
    '❌': r'$\times$',
    '⇒': r'$\Rightarrow$',
    '⟹': r'$\Longrightarrow$',
    '⟺': r'$\Longleftrightarrow$',
    '⇔': r'$\Leftrightarrow$',
    '↔': r'$\leftrightarrow$',
    '≤': r'$\le$',
    '≥': r'$\ge$',
    '≠': r'$\ne$',
    '≈': r'$\approx$',
    '∞': r'$\infty$',
}


# 等宽框线字符 → ASCII 等价物（只在代码块里生效）
BOX_DRAWING = {
    '─': '-', '━': '-', '│': '|', '┃': '|',
    '┌': '+', '┐': '+', '└': '+', '┘': '+',
    '├': '+', '┤': '+', '┬': '+', '┴': '+', '┼': '+',
    '═': '=', '║': '|', '╔': '+', '╗': '+', '╚': '+', '╝': '+',
    '▭': '[ ]',
}


def preprocess(text: str) -> str:
    """把 emoji / 全角装饰符号换成 XeLaTeX 一定能排出来的形式。

    注意：==高亮== 的定界符不在这里去掉——代码里的 == 是字面量（如 `n == 0`），
    必须等代码区抽成占位符之后再处理，见 _inline()。
    """
    # 1. 装饰性标记直接删除
    for ch in STRIP_MARKS:
        text = text.replace(ch, '')
    # 2. 标题行里的 ⚠️ 直接删除，避免变成「### 注意：xxx」这种标题
    text = re.sub(r'^(#{1,6})(.*?)⚠\ufe0f?', r'\1\2', text, flags=re.MULTILINE)
    # 3. 正文里的 ⚠️ / ⚠ → 「注意：」
    text = re.sub(r'⚠\ufe0f?\s*', '注意：', text)
    # 4. ①…⑩
    for k, v in CIRCLED.items():
        text = text.replace(k, v)
    # 5. 数学符号（走 $...$，脚本会保护）
    for k, v in MATH_SYMBOLS.items():
        text = text.replace(k, v)
    # 6. Markdown 里转义过的竖线 \| → 全角竖线，避免 \| 在正文模式下出错
    text = text.replace('\\|', '｜')
    return text



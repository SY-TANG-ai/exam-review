class State:
    NORMAL = "normal"
    IN_CODE = "in_code"
    IN_TABLE = "in_table"
    IN_BLOCKQUOTE = "in_blockquote"


def display_len(s: str) -> int:
    """粗估显示宽度：CJK 记 2，其余记 1。"""
    n = 0
    for ch in s:
        n += 2 if ord(ch) > 0x2E80 else 1
    return n


class Md2Tex:
    def __init__(self, columns=2, strip_ncol=999, fs_body=8.0):
        self.columns = columns
        self.strip_ncol = strip_ncol      # 列数 >= 该值的表格抽到文末通栏排
        self.fs_body = fs_body
        self.state = State.NORMAL
        self.list_stack = []      # [(env, indent)]
        self.table_buffer = []
        self.code_buffer = []
        self.bq_buffer = []
        self.last_heading = ""
        self.large_tables = []    # [(label, tabular_tex)]
        self.out = []

    # ---------------- 主循环 ----------------
    def convert(self, md: str) -> str:
        lines = md.splitlines()
        i = 0
        while i < len(lines):
            line = lines[i]

            # 代码块
            if line.strip().startswith("```"):
                if self.state != State.IN_CODE:
                    self._flush()
                    self.state = State.IN_CODE
                    self.code_buffer = []
                else:
                    self._emit_code()
                    self.state = State.NORMAL
                i += 1
                continue
            if self.state == State.IN_CODE:
                self.code_buffer.append(line)
                i += 1
                continue

            # 空行
            if line.strip() == "":
                self._flush()
                self._close_lists(0)
                i += 1
                continue

            # 分隔线
            if re.fullmatch(r"\s*-{3,}\s*", line):
                self._flush()
                self._close_lists(0)
                self.out.append("\\csheetrule")
                i += 1
                continue

            # 表格
            if self._is_table_line(line):
                if self.state != State.IN_TABLE:
                    self._flush()
                    self.state = State.IN_TABLE
                    self.table_buffer = []
                self.table_buffer.append(line)
                i += 1
                continue
            elif self.state == State.IN_TABLE:
                self._emit_table()
                self.state = State.NORMAL
                continue

            # 引用
            if line.strip().startswith(">"):
                if self.state != State.IN_BLOCKQUOTE:
                    self._flush()
                    self.state = State.IN_BLOCKQUOTE
                    self.bq_buffer = []
                self.bq_buffer.append(line)
                i += 1
                continue
            elif self.state == State.IN_BLOCKQUOTE:
                self._emit_quote()
                self.state = State.NORMAL
                continue

            # 标题
            m = re.match(r"^(#{1,6})\s+(.*)", line)
            if m:
                self._flush()
                self._close_lists(0)
                level = len(m.group(1))
                self._emit_heading(level, self._inline(m.group(2)))
                i += 1
                continue

            # 列表
            ul = re.match(r"^(\s*)[-*+]\s+(.*)", line)
            ol = re.match(r"^(\s*)\d+\.\s+(.*)", line)
            if ul or ol:
                self._flush()
                mm = ul or ol
                indent = len(mm.group(1))
                self._list_item("itemize" if ul else "enumerate", indent,
                                self._inline(mm.group(2)))
                i += 1
                continue

            # 普通段落
            self._flush()
            self.out.append(self._inline(line.strip()) + "\\par")
            i += 1

        self._flush()
        self._close_lists(0)
        return "\n".join(self.out)

    # ---------------- 状态收尾 ----------------
    def _flush(self):
        if self.state == State.IN_TABLE:
            self._emit_table()
            self.state = State.NORMAL
        elif self.state == State.IN_BLOCKQUOTE:
            self._emit_quote()
            self.state = State.NORMAL

    # ---------------- 各类元素 ----------------
    def _emit_heading(self, level, text):
        if level == 1:
            return  # 一级标题由标题块承担
        self.last_heading = text
        cmd = {2: "section", 3: "subsection"}.get(level, "subsubsection")
        self.out.append(f"\\{cmd}*{{{text}}}")

    def _list_item(self, env, indent, text):
        # 缩进每 2 空格算一级；同级复用同一环境
        depth = indent // 2
        while len(self.list_stack) > depth + 1:
            self.out.append(f"\\end{{{self.list_stack.pop()[0]}}}")
        if len(self.list_stack) == depth + 1 and self.list_stack[-1][0] != env:
            self.out.append(f"\\end{{{self.list_stack.pop()[0]}}}")
        while len(self.list_stack) < depth + 1:
            self.out.append(f"\\begin{{{env}}}")
            self.list_stack.append((env, indent))
        self.out.append(f"  \\item {text}")

    def _close_lists(self, target):
        while len(self.list_stack) > target:
            self.out.append(f"\\end{{{self.list_stack.pop()[0]}}}")

    def _is_table_line(self, line):
        s = line.strip()
        return s.startswith("|") and s.count("|") >= 2

    def _emit_table(self):
        if not self.table_buffer:
            return
        rows = []
        for ln in self.table_buffer:
            s = ln.strip()
            if re.fullmatch(r"[\s|\-:+]+", s):
                continue            # 分隔行 | --- | --- |
            cells = s.split("|")
            if cells and cells[0].strip() == "":
                cells = cells[1:]
            if cells and cells[-1].strip() == "":
                cells = cells[:-1]
            rows.append([c.strip() for c in cells])
        if not rows:
            self.table_buffer = []
            return

        ncol = max(len(r) for r in rows)
        rows = [r for r in rows if len(r) == ncol]

        # 列数超过阈值 → 抽到文末通栏排（窄栏里塞不下 4-5 列对比表）
        stripped = ncol >= self.strip_ncol
        width_macro = "\\textwidth" if stripped else "\\linewidth"

        # --- 按内容长度分配列宽 ---
        # 用 sqrt(平均显示宽度) 做权重：长文本列变宽，但不会把短列挤成一条线
        widths = []
        for c in range(ncol):
            lens = [display_len(r[c]) for r in rows] or [4]
            avg = sum(lens) / len(lens)
            widths.append(math.sqrt(max(avg, 6.0)))   # 6 字以下一律按 6 字算
        total = sum(widths)
        fracs = [w / total for w in widths]
        # 单列上限 0.62，防止一列吃满整栏
        fracs = [min(f, 0.62) for f in fracs]
        ssum = sum(fracs)
        # 合计留余量给 tabcolsep，避免 overfull hbox
        fracs = [f / ssum * (0.97 if stripped else 0.95) for f in fracs]
        colspec = "".join(
            f">{{\\raggedright\\arraybackslash}}p{{{f:.3f}{width_macro}}}" for f in fracs
        )

        # 列多则降字号（相对正文缩，但不低于 5pt，否则印出来认不出）
        if stripped:
            fs_pt = max(self.fs_body - 0.4, 5.6)
        elif ncol >= 5:
            fs_pt = self.fs_body - 1.8
        elif ncol == 4:
            fs_pt = self.fs_body - 1.4
        elif ncol == 3:
            fs_pt = self.fs_body - 1.0
        else:
            fs_pt = self.fs_body - 0.6
        fs_pt = max(fs_pt, 5.0)
        fs = f"{fs_pt:.1f}pt"
        bl = f"{fs_pt * 1.26:.1f}pt"

        body = []
        body.append(f"\\begin{{cstab}}{{{colspec}}}{{{fs}}}{{{bl}}}")
        body.append("\\toprule")
        for idx, r in enumerate(rows):
            if idx == 0:
                cells = [f"\\tblheader{{{self._inline(c)}}}" for c in r]
                body.append(" & ".join(cells) + " \\\\")
                body.append("\\midrule")
            else:
                if idx % 2 == 0:
                    body.append("\\rowcolor{TableOddBg}")
                cells = [self._inline(c) for c in r]
                body.append(" & ".join(cells) + " \\\\")
        body.append("\\bottomrule")
        body.append("\\end{cstab}")
        tex = "\n".join(body)

        if stripped:
            self.large_tables.append((self.last_heading, tex))
        else:
            self.out.append(tex)
            # 表后给一点呼吸空间
            self.out.append("\\vspace{0.15em}")
        self.table_buffer = []

    def _emit_code(self):
        if not self.code_buffer:
            return
        self.out.append("\\begin{quote}\\ttfamily")
        for ln in self.code_buffer:
            for k, v in BOX_DRAWING.items():   # 等宽框线 → ASCII（ttfamily 未必有该字形）
                ln = ln.replace(k, v)
            self.out.append(ln.replace("\\", "\\textbackslash{}")
                            .replace("{", "\\{").replace("}", "\\}")
                            .replace("_", "\\_").replace("&", "\\&")
                            .replace("%", "\\%").replace("#", "\\#")
                            .replace("^", "\\textasciicircum{}")
                            .replace("~", "\\textasciitilde{}"))
        self.out.append("\\end{quote}")

    def _emit_quote(self):
        if not self.bq_buffer:
            return
        parts = []
        for ln in self.bq_buffer:
            s = ln.strip()
            if s.startswith(">"):
                s = s[1:].strip()
            s = re.sub(r"^\[![^\]]+\]\s*", "", s)   # 去掉 Obsidian callout 类型标记
            if s:
                parts.append(self._inline(s))
        content = "\\\\".join(parts)   # 保留换行，不挤成一段
        self.out.append(f"\\begin{{quote}}\\csheetquote{{{content}}}\\end{{quote}}")
        self.bq_buffer = []

    # ---------------- 行内 ----------------
    def _inline(self, text: str) -> str:
        store = {}

        def put(val: str, tag: str) -> str:
            key = f"\x00{tag}{len(store)}\x00"
            store[key] = val
            return key

        # 1) 数学区（$$ / $）先抽走，避免被后续正则误伤
        def save_display(m):
            return put(self._math(m.group(1).strip(), display=True), "DM")

        def save_inline(m):
            return put(m.group(0), "IM")

        text = re.sub(r"(?<!\\)\$\$(.+?)\$\$", save_display, text, flags=re.DOTALL)
        text = re.sub(r"(?<!\\)\$([^$]+?)\$", save_inline, text)

        # 2) 行内代码先抽走：代码里的 * _ ~ ^ 都是字面量，不能让 bold/italic 正则碰
        def save_code(m):
            return put("\\csheetcodeinline{" + self._escape(m.group(1)) + "}", "CI")

        text = re.sub(r"`([^`]+?)`", save_code, text)

        # 3) 图片只留 alt，链接只留文字
        text = re.sub(r"!\[([^\]]*)\]\([^)]*\)", r"\1", text)
        text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)

        # 3.5) ==高亮== 去掉定界符（代码区已抽走，这里剩下的才是真高亮）
        text = re.sub(r"==(.+?)==", r"\1", text)

        # 4) 粗体（先做，避免和斜体打架）
        text = re.sub(r"\*\*(.+?)\*\*", r"\\csheetbold{\1}", text)
        text = re.sub(r"__(.+?)__", r"\\csheetbold{\1}", text)
        # 删除线
        text = re.sub(r"~~(.+?)~~", r"\\csheetstrike{\1}", text)
        # 斜体（单个 *，且前后不是 * 或已转义的 \）
        text = re.sub(r"(?<![\*\\])\*([^\*\n]+?)\*(?!\*)", r"\\textit{\1}", text)

        # 5) 剩余普通字符转义
        text = self._escape(text)

        for key, val in store.items():
            text = text.replace(key, val)
        return text

    def _escape(self, text: str) -> str:
        # 数学区与行内代码已抽成占位符，这里只处理剩下的普通字符
        text = text.replace("&", r"\&")
        text = text.replace("%", r"\%")
        text = text.replace("#", r"\#")
        text = text.replace("_", r"\_")
        text = text.replace("$", r"\$")
        text = text.replace("~", r"\textasciitilde{}")
        text = text.replace("^", r"\textasciicircum{}")
        text = text.replace("→", r"$\rightarrow$")
        text = text.replace("←", r"$\leftarrow$")
        text = text.replace("⇒", r"$\Rightarrow$")
        text = text.replace("⇐", r"$\Leftarrow$")
        text = text.replace("↔", r"$\leftrightarrow$")
        text = text.replace("⇔", r"$\Leftrightarrow$")
        text = text.replace("↑", r"$\uparrow$")
        text = text.replace("↓", r"$\downarrow$")
        text = text.replace("−", r"$-$")
        text = text.replace("×", r"$\times$")
        text = text.replace("÷", r"$\div$")
        text = text.replace("±", r"$\pm$")
        text = text.replace("->", r"$\rightarrow$")
        text = text.replace("<-", r"$\leftarrow$")
        return text

    def _math(self, s: str, display=False):
        for a, b in (("→", r"\rightarrow"), ("←", r"\leftarrow"),
                     ("⇒", r"\Rightarrow"), ("↔", r"\leftrightarrow")):
            s = s.replace(a, b)
        return f"\\[{s}\\]" if display else s


